"""失败测乙：双写两轨，异站影子汇总不得充正式。

契约（题面）：
- 异站点落入只读归档，现行汇总改读本站集，读引用不同。
- 混站结栏之后，现行汇总里的站点集合须可区分（正式 vs 影子归档）。
- 失败测乙：贯验把混站影子汇总误标对齐则红。
- 假绿分属结栏与贯验，禁止只改一处。
"""
from __future__ import annotations

import pytest

from app.services import 装载, 结栏, 贯验, 目录
from app.services import 站界


def _混站批() -> dict:
    return {
        "批次编号": "混站-乙",
        "报文": [
            {"报文编号": "Y-1", "站点键": "站-河东", "指标键": "PM25", "读数": 31.0,
             "观测时": "2026-11-25T10:00:00Z"},
            {"报文编号": "Y-2", "站点键": "站-湖西", "指标键": "浊度", "读数": 2.1,
             "观测时": "2026-11-25T10:05:00Z"},
            {"报文编号": "Y-3", "站点键": "站-湖西", "指标键": "浊度", "读数": 2.3,
             "观测时": "2026-11-25T10:15:00Z"},
        ],
    }


def _启用乙() -> None:
    目录.改栏规({"禁混汇总": "乙"})


def test_乙_双写后正式汇总只含本站影子进归档():
    _启用乙()
    装载.装一批(_混站批())
    报告 = 结栏.结当前栏()

    正式 = 目录.汇总列表()
    assert {r["站点键"] for r in 正式} == {"站-河东"}
    assert 报告["锚站"] == "站-河东"
    assert sorted(报告["影子异站"]) == ["站-湖西"]

    归档 = 站界.读影子归档()
    assert {r["站点键"] for r in 归档} == {"站-湖西"}
    assert sum(r["报文数"] for r in 归档) == 2
    # 归档只读：现行正式账与归档读引用不同
    assert all(r["汇总编号"] not in {x["汇总编号"] for x in 正式} for r in 归档)

    # 两轨报文都被消耗，没有遗留
    assert 目录.缓冲列表("在栏") == []
    assert len(目录.缓冲列表("已汇总")) == 3


def test_乙_贯验影子不算正式且误标对齐则红():
    _启用乙()
    装载.装一批(_混站批())
    结栏.结当前栏()

    快照 = 贯验.只读快照()
    # 影子汇总报文不得计入正式汇总报文数
    assert 快照["汇总报文"] == 1
    assert 快照["影子归档报文"] == 2
    果 = 贯验.跑一次()
    assert 果["是否对齐"] is True, "双写两轨本身应对齐"

    # 失败测乙：把影子行误当正式（模拟贯验漏看命运/轨道）必须被抓成撕裂
    from app.db import 连接
    conn = 连接()
    try:
        conn.execute(
            "UPDATE 站点汇总账 SET 命运=? WHERE 命运=?",
            ("已汇总", "影子归档"),
        )
        conn.commit()
    finally:
        conn.close()
    assert 贯验.跑一次()["是否对齐"] is False


def test_乙_裁决接口区分正式与影子站点集():
    _启用乙()
    装载.装一批(_混站批())
    结栏.结当前栏()
    裁决 = 站界.读裁决()
    assert 裁决["策略"] == "双写两轨归档"
    assert 裁决["正式站点集"] == ["站-河东"]
    assert 裁决["异站站点集"] == ["站-湖西"]
    assert 裁决["裁决笔数"] == 2  # 两条异站指纹（按报文钉）


def test_乙_单站成片无影子归档():
    _启用乙()
    体 = {
        "批次编号": "单站-乙",
        "报文": [
            {"报文编号": "SY-1", "站点键": "站-江口", "指标键": "PM25", "读数": 40.0,
             "观测时": "2026-11-25T11:00:00Z"},
        ],
    }
    装载.装一批(体)
    结栏.结当前栏()
    assert 站界.读影子归档() == []
    裁决 = 站界.读裁决()
    assert 裁决["异站站点集"] == []
    assert 贯验.跑一次()["是否对齐"] is True


@pytest.mark.asyncio
async def test_乙_只读接口与正式汇总读引用分离():
    _启用乙()
    装载.装一批(_混站批())
    结栏.结当前栏()

    from app.main import app
    client = app.test_client()
    裁决 = await (await client.get("/api/站界/裁决")).get_json()
    assert 裁决["正式站点集"] == ["站-河东"]
    assert 裁决["异站站点集"] == ["站-湖西"]

    归档 = await (await client.get("/api/站界/影子归档")).get_json()
    assert {r["站点键"] for r in 归档} == {"站-湖西"}

    正式 = await (await client.get("/api/站点汇总账")).get_json()
    assert {r["站点键"] for r in 正式} == {"站-河东"}
