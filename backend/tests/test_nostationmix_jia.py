"""失败测甲：切流账册拒绝跨站拼接。

契约（题面）：
- 异站拒进本趟汇总并钉指纹，现行汇总只含本站（锚站）。
- 混站结栏后，正式汇总行站点键若仍混则红。
- 新增站界裁决只读接口，正式站点集与异站站点集可区分。
- 同成同败：结栏事务内缓冲命运与汇总账一起落库。
"""
from __future__ import annotations

import pytest

from app.services import 装载, 结栏, 贯验, 目录
from app.services import 站界


def _混站批() -> dict:
    return {
        "批次编号": "混站-甲",
        "报文": [
            {"报文编号": "J-1", "站点键": "站-河东", "指标键": "PM25", "读数": 30.0,
             "观测时": "2026-11-25T08:00:00Z"},
            {"报文编号": "J-2", "站点键": "站-河东", "指标键": "PM25", "读数": 34.0,
             "观测时": "2026-11-25T08:10:00Z"},
            {"报文编号": "J-3", "站点键": "站-湖西", "指标键": "浊度", "读数": 1.8,
             "观测时": "2026-11-25T08:05:00Z"},
        ],
    }


def _启用甲() -> None:
    目录.改栏规({"禁混汇总": "甲"})


def test_甲_混站结栏正式汇总只含锚站():
    _启用甲()
    装载.装一批(_混站批())
    报告 = 结栏.结当前栏()

    正式 = 目录.汇总列表()
    正式站点 = {r["站点键"] for r in 正式}
    # 失败测甲：正式汇总行站点键仍混则红
    assert 正式站点 == {"站-河东"}, f"正式汇总混入异站：{正式站点}"
    assert 报告["锚站"] == "站-河东"
    assert sorted(报告["拒拼异站"]) == ["站-湖西"]

    # 异站报文不得被本趟消耗，仍是在栏缓冲
    在栏 = {r["报文编号"] for r in 目录.缓冲列表("在栏")}
    assert 在栏 == {"J-3"}
    已汇总 = {r["报文编号"] for r in 目录.缓冲列表("已汇总")}
    assert 已汇总 == {"J-1", "J-2"}


def test_甲_异站钉指纹且重复结栏不重复记账():
    _启用甲()
    装载.装一批(_混站批())
    结栏.结当前栏()
    裁决一 = 站界.读裁决()
    assert 裁决一["策略"] == "切流账册拒拼"
    assert 裁决一["正式站点集"] == ["站-河东"]
    assert 裁决一["异站站点集"] == ["站-湖西"]
    assert 裁决一["裁决笔数"] == 1

    # 再结一趟：异站仍被拒，指纹幂等，裁决与正式汇总都不得膨胀
    结栏.结当前栏()
    裁决二 = 站界.读裁决()
    assert 裁决二["裁决笔数"] == 1
    assert len(目录.汇总列表()) == 1
    assert {r["报文编号"] for r in 目录.缓冲列表("在栏")} == {"J-3"}


def test_甲_贯验对齐且正式账混入影子行必撕裂():
    _启用甲()
    装载.装一批(_混站批())
    结栏.结当前栏()
    assert 贯验.跑一次()["是否对齐"] is True

    # 假绿防护：非正式命运的行混进正式汇总账，贯验不得标对齐
    from app.db import 连接
    from app.seed import 此刻
    conn = 连接()
    try:
        conn.execute(
            """INSERT INTO 站点汇总账(汇总编号,栏号,站点键,指标键,报文数,均值,物化时,命运)
               VALUES (?,?,?,?,?,?,?,?)""",
            ("汇-影子-1", "B-demo", "站-湖西", "浊度", 1, 1.8, 此刻(), "影子归档"),
        )
        conn.commit()
    finally:
        conn.close()
    assert 贯验.跑一次()["是否对齐"] is False


def test_甲_单站成片不产生异站():
    _启用甲()
    体 = {
        "批次编号": "单站-甲",
        "报文": [
            {"报文编号": "S-1", "站点键": "站-北岭", "指标键": "PM25", "读数": 20.0,
             "观测时": "2026-11-25T09:00:00Z"},
            {"报文编号": "S-2", "站点键": "站-北岭", "指标键": "PM25", "读数": 22.0,
             "观测时": "2026-11-25T09:10:00Z"},
        ],
    }
    装载.装一批(体)
    结栏.结当前栏()
    裁决 = 站界.读裁决()
    assert 裁决["异站站点集"] == []
    assert 裁决["正式站点集"] == ["站-北岭"]
    assert 贯验.跑一次()["是否对齐"] is True


@pytest.mark.asyncio
async def test_甲_站界裁决只读接口可见禁混():
    _启用甲()
    装载.装一批(_混站批())
    结栏.结当前栏()

    from app.main import app
    client = app.test_client()
    resp = await client.get("/api/站界/裁决")
    assert resp.status_code == 200
    data = await resp.get_json()
    assert data["策略"] == "切流账册拒拼"
    assert data["正式站点集"] == ["站-河东"]
    assert data["异站站点集"] == ["站-湖西"]
    assert data["裁决笔数"] == 1
